// ── Table-based timings ───────────────────────────────────
// Tables are configured on the restaurant (partner) platform; the admin
// portal shows them read-only. Each table has a name and its availability
// per day — a day can have multiple time ranges (split slots), and days
// with no ranges are closed.
export type TableDay = 'mon' | 'tue' | 'wed' | 'thu' | 'fri' | 'sat' | 'sun'
export interface TableTimeRange {
  start: string
  end: string
  /**
   * When true the slot is disabled: greyed out in the Table Timings view and
   * unavailable for admin to select on new interest tables (PP4 AC6/AC6a).
   * Slots are never permanently deleted — only disabled or re-enabled.
   */
  disabled?: boolean
}
export interface TableDaySlots {
  day: TableDay
  ranges: TableTimeRange[]
}
export interface RestaurantTable {
  id: string
  name: string
  /** Per-day availability. Days absent from this list are closed. */
  slots: TableDaySlots[]
  /** When true the table timing is hidden from diners (still editable by the partner). */
  hidden?: boolean
}

