// A combo is a fixed-price deal (name, thumbnail, what's included, one
// price). This same pool is reused by the Interest Table creation flow.
/**
 * Prix-fixe menu ("combo"). Partner-authored, read-only in the admin portal.
 * Each menu has a price and one or more sections; a section offers a
 * choice-of-N from its item list (shown as chips in the UI).
 */
export interface ComboSection {
  name: string
  /** How many items the diner picks from this section (choice of N). */
  choice: number
  items: string[]
}

export interface Combo {
  id: string
  name: string
  price: number
  description?: string
  /** Optional combo photo (object/data URL in the prototype). */
  photo?: string
  sections: ComboSection[]
  /** When true the combo menu is hidden from diners (still editable by the partner). */
  hidden?: boolean
}

